/* Output SIZE zero bytes.  We ignore the FILE argument since the
   functions we're calling to perform the output just use
   asm_out_file.  */
//原型 #define ASM_OUTPUT_SKIP(FILE, N) nvptx有实现
static void outputSkip_cb (TargetAsmOut *targetAsmOut, unsigned HOST_WIDE_INT size)
{
   TargetPtxAsmOut *self=(TargetPtxAsmOut *)targetAsmOut;

   /* Finish the current fragment, if it's started.  */
   if (self->init_frag.offset){
      unsigned part = self->init_frag.size - self->init_frag.offset;
      part = MIN (part, (unsigned)size);
      size -= part;
      nvptx_assemble_value(self,0, part);
   }

   /* If this skip doesn't terminate the initializer, write as many
   remaining pieces as possible directly.  */
   if (size < self->init_frag.remaining * self->init_frag.size){
      while (size >= self->init_frag.size){
         size -= self->init_frag.size;
         output_init_frag(self,NULL_RTX);
      }
      if (size)
         nvptx_assemble_value(self,0, size);
   }
}

