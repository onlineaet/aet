static void output_init_frag (TargetPtxAsmOut *self,rtx sym)
{
   MtcsMode *mtcsMode=MTCS_GET_MODE_OBJECT(self);
   MtcsTarget *mtcsTarget=(MtcsTarget *)mtcsMode->target;
   MtcsAsm *mtcsAsm=mtcs_target_get_asm(mtcsTarget);
   MtcsOutput *mtcsOutput=mtcs_target_get_output(mtcsTarget);

   fprintf (mtcsAsm->asmFile, self->init_frag.started ? ", " : " = { ");
   unsigned HOST_WIDE_INT val = self->init_frag.val;
   n_debug("targetptxasmout.c -----nvptx.cc -----180-- output_init_frag val:%d\n",val);

   self->init_frag.started = true;
   self->init_frag.val = 0;
   self->init_frag.offset = 0;
   self->init_frag.remaining--;

   if (sym){
      bool function = (SYMBOL_REF_DECL (sym)  && (TREE_CODE (SYMBOL_REF_DECL (sym)) == FUNCTION_DECL));
      if (!function)
         fprintf (mtcsAsm->asmFile, "generic(");
      mtcs_output_address (mtcsOutput,VOIDmode, sym);
      if (!function)
         fprintf (mtcsAsm->asmFile, ")");
      if (val)
         fprintf (mtcsAsm->asmFile, " + ");
   }

   if (!sym || val)
      fprintf (mtcsAsm->asmFile, HOST_WIDE_INT_PRINT_DEC, val);
}

/* Add value VAL of size SIZE to the data we're emitting, and keep
   writing out chunks as they fill up.  */
static void nvptx_assemble_value (TargetPtxAsmOut *self,unsigned HOST_WIDE_INT val, unsigned size)
{
   n_debug("targetptxasmout.c -----nvptx.cc -----53-- void nvptx_assemble_value val:%d size:%d\n",val,size);
   bool negative_p = val & (HOST_WIDE_INT_1U << (HOST_BITS_PER_WIDE_INT - 1));
   /* Avoid undefined behaviour.  */
   if (size * BITS_PER_UNIT < HOST_BITS_PER_WIDE_INT)
      val &= (HOST_WIDE_INT_1U << (size * BITS_PER_UNIT)) - 1;

   for (unsigned part = 0; size; size -= part){
      if (part * BITS_PER_UNIT == HOST_BITS_PER_WIDE_INT)
         /* Avoid undefined behaviour.  */
         val = negative_p ? -1 : 0;
      else
         val >>= (part * BITS_PER_UNIT);
      part = self->init_frag.size - self->init_frag.offset;
      part = MIN (part, size);

      unsigned HOST_WIDE_INT partial = val << (self->init_frag.offset * BITS_PER_UNIT);
      self->init_frag.val |= partial & self->init_frag.mask;
      self->init_frag.offset += part;
      if (self->init_frag.offset == self->init_frag.size)
         output_init_frag (self,NULL);
   }
}


