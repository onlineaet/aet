/* Emit soft stack frame setup sequence.  */
static void init_softstack_frame (TargetPtxAsmOut *self,FILE *file, unsigned alignment, HOST_WIDE_INT size)
{
   MtcsMode *mtcsMode=MTCS_GET_MODE_OBJECT(self);
   MtcsTarget *mtcsTarget=(MtcsTarget *)mtcsMode->target;
   MtcsReg *mtcsReg=mtcs_target_get_reg(mtcsTarget);
   MtcsFunc *mtcsFunc=mtcs_target_get_func(mtcsTarget);
   MtcsRtlData *mtcsRtlData=mtcs_func_get_rtl_data(mtcsFunc);

   //  struct ptx_machine_function *nvptxMachine=(struct ptx_machine_function *)mtcsFunc->machine;
   struct ptx_machine_function *nvptxMachine=(struct ptx_machine_function *)cfun->machine;

   /* Maintain 64-bit stack alignment.  */
   unsigned keep_align = PTX_BIGGEST_ALIGNMENT / BITS_PER_UNIT;
   size = ROUND_UP (size, keep_align);
   int bits = PTX_POINTER_SIZE;
   const char *reg_stack = mtcs_reg_get_reg_name(mtcsReg,PTX_STACK_POINTER_REGNUM);//reg_names[STACK_POINTER_REGNUM];
   const char *reg_frame = mtcs_reg_get_reg_name(mtcsReg,PTX_FRAME_POINTER_REGNUM);//reg_names[FRAME_POINTER_REGNUM];
   const char *reg_sspslot = mtcs_reg_get_reg_name(mtcsReg,PTX_SOFTSTACK_SLOT_REGNUM);//reg_names[SOFTSTACK_SLOT_REGNUM];
   const char *reg_sspprev = mtcs_reg_get_reg_name(mtcsReg,PTX_SOFTSTACK_PREV_REGNUM);//reg_names[SOFTSTACK_PREV_REGNUM];
   fprintf (file, "\t.reg.u%d %s;\n", bits, reg_stack);
   fprintf (file, "\t.reg.u%d %s;\n", bits, reg_frame);
   fprintf (file, "\t.reg.u%d %s;\n", bits, reg_sspslot);
   fprintf (file, "\t.reg.u%d %s;\n", bits, reg_sspprev);
   fprintf (file, "\t{\n");
   fprintf (file, "\t\t.reg.u32 %%fstmp0;\n");
   fprintf (file, "\t\t.reg.u%d %%fstmp1;\n", bits);
   fprintf (file, "\t\t.reg.u%d %%fstmp2;\n", bits);
   fprintf (file, "\t\tmov.u32 %%fstmp0, %%tid.y;\n");
   fprintf (file, "\t\tmul%s.u32 %%fstmp1, %%fstmp0, %d;\n", bits == 64 ? ".wide" : ".lo", bits / 8);
   fprintf (file, "\t\tmov.u%d %%fstmp2, __nvptx_stacks;\n", bits);

   /* Initialize %sspslot = &__nvptx_stacks[tid.y].  */
   fprintf (file, "\t\tadd.u%d %s, %%fstmp2, %%fstmp1;\n", bits, reg_sspslot);

   /* Initialize %sspprev = __nvptx_stacks[tid.y].  */
   fprintf (file, "\t\tld.shared.u%d %s, [%s];\n", bits, reg_sspprev, reg_sspslot);

   /* Initialize %frame = %sspprev - size.  */
   fprintf (file, "\t\tsub.u%d %s, %s, " HOST_WIDE_INT_PRINT_DEC ";\n",bits, reg_frame, reg_sspprev, size);

   /* Apply alignment, if larger than 64.  */
   if (alignment > keep_align)
      fprintf (file, "\t\tand.b%d %s, %s, %d;\n",bits, reg_frame, reg_frame, -alignment);

   //size = crtl->outgoing_args_size;
   size =mtcsRtlData/*!crtl*/->outgoing_args_size.coeffs[0];
   gcc_assert (size % keep_align == 0);

   /* Initialize %stack.  */
   fprintf (file, "\t\tsub.u%d %s, %s, " HOST_WIDE_INT_PRINT_DEC ";\n",bits, reg_stack, reg_frame, size);

   if (!mtcsRtlData/*!crtl*/->is_leaf)
      fprintf (file, "\t\tst.shared.u%d [%s], %s;\n",bits, reg_sspslot, reg_stack);
   fprintf (file, "\t}\n");
   nvptxMachine->has_softstack = true;
   self->need_softstack_decl = true;
}

