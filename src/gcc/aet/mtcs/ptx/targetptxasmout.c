static void init_asm_int_op(TargetPtxAsmOut *self)
{
   TargetAsmOut *targetAsmOut=(TargetAsmOut *)self;

   targetAsmOut->aligned_op.hi="\t.short\t"; //原型 TARGET_ASM_ALIGNED_HI_OP target-def.h
   targetAsmOut->aligned_op.psi=NULL;
   targetAsmOut->aligned_op.si="\t.long\t";  //原型 TARGET_ASM_ALIGNED_SI_OP target-def.h
   targetAsmOut->aligned_op.pdi=NULL;
   targetAsmOut->aligned_op.di=NULL;
   targetAsmOut->aligned_op.pti=NULL;
   targetAsmOut->aligned_op.ti=NULL;

   targetAsmOut->unaligned_op.hi=NULL;
   targetAsmOut->unaligned_op.psi=NULL;
   targetAsmOut->unaligned_op.si=NULL;
   targetAsmOut->unaligned_op.pdi=NULL;
   targetAsmOut->unaligned_op.di=NULL;
   targetAsmOut->unaligned_op.pti=NULL;
   targetAsmOut->unaligned_op.ti=NULL;
   targetAsmOut->byte_op ="\t.byte\t";
}



static void targetPtxAsmOutInit(TargetPtxAsmOut *self)
{
   TargetAsmOut *targetAsmOut=(TargetAsmOut *)self;
   //原型targetm.asm_out.print_operand_address #define TARGET_PRINT_OPERAND_ADDRESS default_print_operand_address
   targetAsmOut->print_operand_address=printOperandAddress_cb;
   //原型targetm.asm_out.print_operand_address #define TARGET_PRINT_OPERAND_ADDRESS default_print_operand_address
   targetAsmOut->print_operand=printOperand_cb;
   //原型  targetm.asm_out.file_start ();#define TARGET_ASM_FILE_START nvptx_file_start
   targetAsmOut->file_start=fileStart_cb;
   //原型 targetm.asm_out.declare_constant_name (asm_out_file, label, exp, size); #define TARGET_ASM_DECLARE_CONSTANT_NAME default_asm_declare_constant_name
   targetAsmOut->declare_constant_name=declareConstantName_cb;
   //原型 TARGET_ASM_DECL_END 无缺省实现
   targetAsmOut->decl_end=declEnd_cb;
   //原型targetm.asm_out.globalize_label (file, name); #define TARGET_ASM_GLOBALIZE_LABEL default_globalize_label
   targetAsmOut->globalize_label=globalizeLabel_cb;
   //原型  targetm.asm_out.print_operand_punct_valid_p ((unsigned char) *p)
   //#define TARGET_PRINT_OPERAND_PUNCT_VALID_P nvptx_print_operand_punct_valid_p
   targetAsmOut->print_operand_punct_valid_p=printOperandPunctValidP_cb;
   //原型 targetm.asm_out.file_end (); #define TARGET_ASM_FILE_END nvptx_file_end
   targetAsmOut->file_end=fileEnd_cb;
   //原型 targetm.asm_out.assemble_undefined_decl (asm_out_file, name, decl); #define TARGET_ASM_ASSEMBLE_UNDEFINED_DECL nvptx_assemble_undefined_decl
   targetAsmOut->assemble_undefined_decl=assembleUndefinedDecl_cb;
   //原型 targetm.asm_out.integer#define TARGET_ASM_INTEGER nvptx_assemble_integer
   targetAsmOut->integer=integer_cb;
   //原型 targetm.asm_out.globalize_decl_name (asm_out_file, decl);#define TARGET_ASM_GLOBALIZE_DECL_NAME default_globalize_decl_name
   targetAsmOut->globalize_decl_name=globalizeDeclName_cb;

   //gcc 旧实现采用的宏，原来声明在MtcsTarget，现在移到 TargetAsmOut
   //旧实现中用到宏的有 1.ASM_OUTPUT_SKIP ASM_OUTPUT_ALIGNED_DECL_COMMON ASM_DECLARE_OBJECT_NAME ASM_OUTPUT_ALIGNED_DECL_LOCAL
   //原型 #define ASM_OUTPUT_SKIP(FILE, N) nvptx有实现
   targetAsmOut->output_skip=outputSkip_cb;
   //原型 #define ASM_OUTPUT_ALIGNED_DECL_COMMON(FILE, DECL, NAME, SIZE, ALIGN)   nvptx有实现
   targetAsmOut->output_aligned_decl_common=outputAlignedDeclCommon_cb;
   //原型 #define ASM_DECLARE_OBJECT_NAME(FILE, NAME, DECL)  nvptx_declare_object_name (FILE, NAME, DECL)
   targetAsmOut->declare_object_name=declareObjectName_cb;
   //原型 #define ASM_OUTPUT_ALIGNED_DECL_LOCAL(FILE, DECL, NAME, SIZE, ALIGN)  nvptx_output_aligned_decl (FILE, NAME, DECL, SIZE, ALIGN)
   targetAsmOut->output_aligned_decl_local=outputAlignedDeclLocal_cb;
   //ASM_OUTPUT_LABELREF 缺省实现，AMD的gcn实现不同
   targetAsmOut->output_labelref=outputLabelref_cb;
   //原型 #define ASM_OUTPUT_DEF(FILE,LABEL1,LABEL2)
   targetAsmOut->output_def = outputDef_cb;
   //原型 #define ASM_OUTPUT_ASCII(FILE, STR, LENGTH) nvptx有实现
   targetAsmOut->output_ascii=outputAscii_cb;
   //实现ASM_DECLARE_FUNCTION_NAME(FILE, NAME, DECL)
   targetAsmOut->declare_function_name=declareFunctionName_cb;
   //TARGET_ASM_MARK_DECL_PRESERVED gcc中的实现是hook_void_constcharptr 声明在gcc/targetdef
   targetAsmOut->mark_decl_preserved =markDeclPreserved_cb;
   //------结束类方法赋值-----------------
   init_asm_int_op(self);
}

TargetPtxAsmOut *target_ptx_asm_out_new(MtcsMode *mtcsMode)
{
   TargetPtxAsmOut *self = n_slice_alloc0 (sizeof(TargetPtxAsmOut));
   mtcs_component_set_mode((MtcsComponent*)self,mtcsMode);
   target_asm_out_init((TargetAsmOut*)self);
   targetPtxAsmOutInit(self);
   return self;
}

