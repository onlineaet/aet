//原型 targetm.asm_out.file_end (); #define TARGET_ASM_FILE_END nvptx_file_end
static void fileEnd_cb(TargetAsmOut *targetAsmOut)
{
   TargetPtxAsmOut *self=(TargetPtxAsmOut *)targetAsmOut;
   MtcsMode *mtcsMode=MTCS_GET_MODE_OBJECT(self);
   MtcsTarget *mtcsTarget=(MtcsTarget *)mtcsMode->target;
   MtcsFunc *mtcsFunc=mtcs_target_get_func(mtcsTarget);
   MtcsPtxFunc *mtcsPtxFunc=(MtcsPtxFunc *)mtcsFunc;
   MtcsAsm *mtcsAsm=mtcs_target_get_asm(mtcsTarget);
   MtcsPtxOutput *mtcsPtxOutput=(MtcsPtxOutput *)mtcs_target_get_output(mtcsTarget);

   n_debug("targetptxasmout.c nvptx.cc nvptx_file_end 00 \n");
   mtcs_ptx_func_file_end(mtcsPtxFunc);
   //把extern 函数声明 写到文件前
   fclose(mtcsAsm->asmFile);

   //int seek= fseek(mtcsAsm->asmFile,0,SEEK_SET);
   FILE *sourceFile=fopen(mtcsAsm->asmFileName,"r");
   NString *brr=n_string_sized_new(2048*1024);
   int len=fread(brr->str,1,2048*1024,sourceFile);
   brr->str[len]='\0';
   brr->len=len;
   fclose(sourceFile);

   fclose(mtcsAsm->asmVarDeclFile);
   FILE *varDeclFile=fopen(mtcsAsm->asmVarDeclFileName,"r");
   char varDeclBuffer[1024*512];
   int  varDeclLen = fread(varDeclBuffer,1,1024*512,varDeclFile);
   varDeclBuffer[varDeclLen]='\0';
   fclose(varDeclFile);
   char *fndeclAsm=mtcs_ptx_asm_get_all_fun_decl_asm((MtcsPtxAsm *)mtcsAsm);
   NString *declStr=n_string_new("");
   if(fndeclAsm)
      n_string_append(declStr,fndeclAsm);
   if(varDeclLen>0)
      n_string_append(declStr,varDeclBuffer);
   //是否有.file 2 "xxxx.c"调试文件
   char *debgFile = mtcs_ptx_output_get_debug_file(mtcsPtxOutput);
   if(debgFile)
      n_string_append(declStr,debgFile);

   n_string_replace(brr,REPLACE_FUNC_DECL_LOCATION,declStr->str,1);
   mtcsAsm->asmFile=fopen(mtcsAsm->asmFileName,"w");
   fputs (brr->str, mtcsAsm->asmFile);
   n_string_free(brr,TRUE);
   n_string_free(declStr,TRUE);
}

